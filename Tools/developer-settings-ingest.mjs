async function main() {
  const inputPath = process.argv[2];
  if (!inputPath) {
    throw new Error("Usage: Tools/developer-settings-ingest.mjs <submission.json>");
  }

  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const snapshot = JSON.parse(await fs.readFile(inputPath, "utf8"));
  const generated = generateDefaultsSources(snapshot);
  const outputPaths = {
    coreModels: path.join(repoRoot, "Packages/Sources/CoreModels/Tuning/CoreDeveloperSettingsDefaults.swift"),
    visuals: path.join(repoRoot, "Packages/Sources/Visuals/DeveloperSettings/VisualDeveloperSettingsDefaults.swift")
  };

  await fs.mkdir(path.dirname(outputPaths.coreModels), { recursive: true });
  await fs.mkdir(path.dirname(outputPaths.visuals), { recursive: true });
  await fs.writeFile(outputPaths.coreModels, generated.coreModels);
  await fs.writeFile(outputPaths.visuals, generated.visuals);

  console.log(`Updated ${path.relative(repoRoot, outputPaths.coreModels)}`);
  console.log(`Updated ${path.relative(repoRoot, outputPaths.visuals)}`);
  console.log(`Source: ${snapshot.source.appVersion} (${snapshot.source.buildNumber}) exported at ${snapshot.exportedAt}`);
}

function assertType(object, keyPath, predicate, expectedType) {
  const value = valueAt(object, keyPath);
  if (!predicate(value)) {
    throw new Error(`${keyPath} must be a ${expectedType}`);
  }
}

function valueAt(object, keyPath) {
  return keyPath.split(".").reduce((value, key) => value?.[key], object);
}

function formatNumber(value) {
  return Number.isInteger(value) ? String(value) : String(value);
}

if (process.argv[1] && import.meta.url === new URL(process.argv[1], "file:").href) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
